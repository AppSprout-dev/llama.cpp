// ============================================================================
// Rotation matrix — Gram-Schmidt QR of deterministic Gaussian matrix
// ============================================================================

struct tq_rotation {
    uint32_t dim;
    std::vector<float> Q; // (dim, dim) row-major orthogonal matrix

    tq_rotation(uint32_t dim, uint32_t seed) : dim(dim), Q(dim * dim) {
        // Generate random Gaussian matrix
        std::mt19937 rng(seed);
        std::normal_distribution<float> dist(0.0f, 1.0f);

        std::vector<float> A(dim * dim);
        for (size_t i = 0; i < dim * dim; ++i) {
            A[i] = dist(rng);
        }

        // Modified Gram-Schmidt QR decomposition
        // Q = orthogonalized columns of A
        for (uint32_t j = 0; j < dim; ++j) {
            // Copy column j of A into Q
            for (uint32_t i = 0; i < dim; ++i) {
                Q[i * dim + j] = A[i * dim + j];
            }

            // Orthogonalize against previous columns
            for (uint32_t k = 0; k < j; ++k) {
                float dot = 0.0f;
                for (uint32_t i = 0; i < dim; ++i) {
                    dot += Q[i * dim + k] * Q[i * dim + j];
                }
                for (uint32_t i = 0; i < dim; ++i) {
                    Q[i * dim + j] -= dot * Q[i * dim + k];
                }
            }

            // Normalize
            float norm = 0.0f;
            for (uint32_t i = 0; i < dim; ++i) {
                norm += Q[i * dim + j] * Q[i * dim + j];
            }
            norm = std::sqrt(norm);
            if (norm > 1e-10f) {
                for (uint32_t i = 0; i < dim; ++i) {
                    Q[i * dim + j] /= norm;
                }
            }
        }

        // Ensure proper rotation (det = +1): flip sign of columns where R diagonal is negative
        // R[j,j] = dot(original_col_j, Q_col_j)
        for (uint32_t j = 0; j < dim; ++j) {
            float r_jj = 0.0f;
            for (uint32_t i = 0; i < dim; ++i) {
                r_jj += A[i * dim + j] * Q[i * dim + j];
            }
            if (r_jj < 0.0f) {
                for (uint32_t i = 0; i < dim; ++i) {
                    Q[i * dim + j] = -Q[i * dim + j];
                }
            }
        }
    }

    // y = x @ Q^T  (rotate forward: multiply by transpose)
    // x: (dim,), y: (dim,)
    void rotate_forward(const float * x, float * y) const {
        for (uint32_t j = 0; j < dim; ++j) {
            float sum = 0.0f;
            // Q^T[j, i] = Q[i, j] (column j of Q)
            for (uint32_t i = 0; i < dim; ++i) {
                sum += x[i] * Q[i * dim + j];
            }
            y[j] = sum;
        }
    }

    // y = x @ Q  (rotate backward: multiply by Q)
    // x: (dim,), y: (dim,)
    void rotate_backward(const float * x, float * y) const {
        for (uint32_t j = 0; j < dim; ++j) {
            float sum = 0.0f;
            // Q[j, i] = row j of Q
            for (uint32_t i = 0; i < dim; ++i) {
                sum += x[i] * Q[j * dim + i];
            }
            y[j] = sum;
        }
    }
};

// Cache rotation matrices by (dim, seed)
static std::mutex s_rotation_mutex;
static std::vector<tq_rotation> s_rotations;

static const tq_rotation & get_rotation(uint32_t dim, uint32_t seed) {
    std::lock_guard<std::mutex> lock(s_rotation_mutex);
    for (const auto & r : s_rotations) {
        if (r.dim == dim) {
            return r;
        }
    }
    s_rotations.emplace_back(dim, seed);
    return s_rotations.back();
}

