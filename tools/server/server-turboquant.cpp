// Searchsorted: find insertion point for val in sorted array boundaries[0..n-1]
static inline uint8_t searchsorted(const float * boundaries, uint32_t n, float val) {
    uint32_t lo = 0, hi = n;
    while (lo < hi) {
        uint32_t mid = (lo + hi) / 2;
        if (boundaries[mid] < val) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    return (uint8_t)lo;
}

// Pack 3-bit indices: 8 indices → 3 bytes
static void pack_3bit(const uint8_t * indices, uint32_t n, uint8_t * packed) {
    // Pack groups of 8 indices into 3 bytes (24 bits)
    uint32_t full_groups = n / 8;
    uint32_t remainder = n % 8;

    for (uint32_t g = 0; g < full_groups; ++g) {
        const uint8_t * src = indices + g * 8;
        uint32_t bits = 0;
        for (int i = 7; i >= 0; --i) {
            bits = (bits << 3) | (src[i] & 0x7);
        }
        packed[g * 3 + 0] = (uint8_t)(bits & 0xFF);
        packed[g * 3 + 1] = (uint8_t)((bits >> 8) & 0xFF);
        packed[g * 3 + 2] = (uint8_t)((bits >> 16) & 0xFF);
    }

    if (remainder > 0) {
        uint32_t bits = 0;
        const uint8_t * src = indices + full_groups * 8;
        for (int i = (int)remainder - 1; i >= 0; --i) {
            bits = (bits << 3) | (src[i] & 0x7);
        }
        uint32_t packed_bytes = (remainder * 3 + 7) / 8;
        uint8_t * dst = packed + full_groups * 3;
        for (uint32_t b = 0; b < packed_bytes; ++b) {
            dst[b] = (uint8_t)((bits >> (b * 8)) & 0xFF);
        }
    }
}

// Unpack 3-bit indices
static void unpack_3bit(const uint8_t * packed, uint32_t n, uint8_t * indices) {
    uint32_t full_groups = n / 8;
    uint32_t remainder = n % 8;

    for (uint32_t g = 0; g < full_groups; ++g) {
        uint32_t bits = packed[g * 3 + 0]
                      | ((uint32_t)packed[g * 3 + 1] << 8)
                      | ((uint32_t)packed[g * 3 + 2] << 16);
        uint8_t * dst = indices + g * 8;
        for (uint32_t i = 0; i < 8; ++i) {
            dst[i] = (uint8_t)(bits & 0x7);
            bits >>= 3;
        }
    }

    if (remainder > 0) {
        uint32_t packed_bytes = (remainder * 3 + 7) / 8;
        uint32_t bits = 0;
        const uint8_t * src = packed + full_groups * 3;
        for (int b = (int)packed_bytes - 1; b >= 0; --b) {
            bits = (bits << 8) | src[b];
        }
        uint8_t * dst = indices + full_groups * 8;
        for (uint32_t i = 0; i < remainder; ++i) {
            dst[i] = (uint8_t)(bits & 0x7);
            bits >>= 3;
        }
    }
}

// Pack 4-bit indices: 2 indices per byte
static void pack_4bit(const uint8_t * indices, uint32_t n, uint8_t * packed) {
    uint32_t pairs = n / 2;
    for (uint32_t i = 0; i < pairs; ++i) {
        packed[i] = (indices[i * 2] & 0xF) | ((indices[i * 2 + 1] & 0xF) << 4);
    }
    if (n % 2) {
        packed[pairs] = indices[n - 1] & 0xF;
    }
}

// Unpack 4-bit indices
static void unpack_4bit(const uint8_t * packed, uint32_t n, uint8_t * indices) {
    uint32_t pairs = n / 2;
    for (uint32_t i = 0; i < pairs; ++i) {
        indices[i * 2]     = packed[i] & 0xF;
        indices[i * 2 + 1] = (packed[i] >> 4) & 0xF;
    }
    if (n % 2) {
        indices[n - 1] = packed[pairs] & 0xF;
    }
}

// Compute packed size in bytes for n elements at given bits
static uint32_t packed_size(uint32_t n, uint8_t bits) {
    if (bits == 3) {
        uint32_t full = (n / 8) * 3;
        uint32_t rem = n % 8;
        return full + (rem > 0 ? (rem * 3 + 7) / 8 : 0);
    }
    if (bits == 4) {
        return (n + 1) / 2;
    }
    return n; // fallback: 1 byte per index
}

// Quantize cell_count vectors of dimension dim from fp16 → compressed indices + norms
static void tq_quantize_vectors(
    const ggml_fp16_t * src, uint32_t cell_count, uint32_t dim,
    uint8_t bits, uint8_t * dst_indices, float * dst_norms)
{
    const float * boundaries = tq_get_boundaries(dim, bits);
    if (!boundaries) return; // unsupported dim/bits combination
    uint32_t n_boundaries = (1u << bits) - 1;
    const tq_rotation & rot = get_rotation(dim, 42);

    std::vector<float> vec(dim);
    std::vector<float> rotated(dim);
    std::vector<uint8_t> indices(dim);

    for (uint32_t c = 0; c < cell_count; ++c) {
        // Convert fp16 → fp32
        const ggml_fp16_t * row = src + c * dim;
        for (uint32_t d = 0; d < dim; ++d) {
            vec[d] = ggml_fp16_to_fp32(row[d]);
        }

        // Compute L2 norm
        float norm = 0.0f;
        for (uint32_t d = 0; d < dim; ++d) {
            norm += vec[d] * vec[d];
        }
        norm = std::sqrt(norm);
        dst_norms[c] = norm;

        // Normalize
        if (norm > 1e-10f) {
            float inv_norm = 1.0f / norm;
            for (uint32_t d = 0; d < dim; ++d) {
                vec[d] *= inv_norm;
            }
        }

        // Rotate: y = x @ Q^T
        rot.rotate_forward(vec.data(), rotated.data());

        // Scalar quantize each coordinate
        for (uint32_t d = 0; d < dim; ++d) {
            indices[d] = searchsorted(boundaries, n_boundaries, rotated[d]);
        }

        // Pack indices
        uint32_t ps = packed_size(dim, bits);
        if (bits == 3) {
            pack_3bit(indices.data(), dim, dst_indices + c * ps);
        } else {
            pack_4bit(indices.data(), dim, dst_indices + c * ps);
        }
    }
}

// Dequantize compressed indices + norms → fp16 vectors
static void tq_dequantize_vectors(
    const uint8_t * src_indices, const float * src_norms,
    uint32_t cell_count, uint32_t dim, uint8_t bits,
    ggml_fp16_t * dst)
{
    const float * centroids = tq_get_centroids(dim, bits);
    if (!centroids) return; // unsupported dim/bits combination
    const tq_rotation & rot = get_rotation(dim, 42);

    std::vector<uint8_t> indices(dim);
    std::vector<float> rotated(dim);
    std::vector<float> vec(dim);

    uint32_t ps = packed_size(dim, bits);

    for (uint32_t c = 0; c < cell_count; ++c) {
        // Unpack indices
        if (bits == 3) {
            unpack_3bit(src_indices + c * ps, dim, indices.data());
        } else {
            unpack_4bit(src_indices + c * ps, dim, indices.data());
        }

        // Centroid lookup
        for (uint32_t d = 0; d < dim; ++d) {
            rotated[d] = centroids[indices[d]];
        }

        // Inverse rotate: y = x @ Q
        rot.rotate_backward(rotated.data(), vec.data());

        // Rescale by norm
        float norm = src_norms[c];
        for (uint32_t d = 0; d < dim; ++d) {
            vec[d] *= norm;
        }

        // Convert fp32 → fp16
        ggml_fp16_t * row = dst + c * dim;
        for (uint32_t d = 0; d < dim; ++d) {
            row[d] = ggml_fp32_to_fp16(vec[d]);
        }
    }
}

// ============================================================================
// Q8 quantization for recurrent state (F32 tensors)
// Per-row affine quantization: val = scale * quant + min
// ============================================================================

struct q8_row_header {
    float scale;
    float min_val;
};

// Quantize F32 rows to Q8 (uint8) with per-row scale+min
static void q8_quantize_rows(
    const float * src, uint32_t n_rows, uint32_t row_dim,
    uint8_t * dst_quant, q8_row_header * dst_headers)
{
    for (uint32_t r = 0; r < n_rows; ++r) {
        const float * row = src + r * row_dim;

        // Find min/max
        float rmin = row[0], rmax = row[0];
        for (uint32_t d = 1; d < row_dim; ++d) {
            if (row[d] < rmin) rmin = row[d];
            if (row[d] > rmax) rmax = row[d];
        }

        float range = rmax - rmin;
        float scale = range > 1e-10f ? range / 255.0f : 0.0f;
        float inv_scale = scale > 1e-10f ? 1.0f / scale : 0.0f;

        dst_headers[r].scale = scale;
        dst_headers[r].min_val = rmin;

        uint8_t * qrow = dst_quant + r * row_dim;
        for (uint32_t d = 0; d < row_dim; ++d) {
            float normalized = (row[d] - rmin) * inv_scale;
            int q = (int)(normalized + 0.5f);
            qrow[d] = (uint8_t)(q < 0 ? 0 : (q > 255 ? 255 : q));
        }
    }
}

// Dequantize Q8 back to F32
static void q8_dequantize_rows(
    const uint8_t * src_quant, const q8_row_header * src_headers,
    uint32_t n_rows, uint32_t row_dim, float * dst)
{
    for (uint32_t r = 0; r < n_rows; ++r) {
        float scale = src_headers[r].scale;
        float min_val = src_headers[r].min_val;
        const uint8_t * qrow = src_quant + r * row_dim;
        float * out = dst + r * row_dim;

        for (uint32_t d = 0; d < row_dim; ++d) {
            out[d] = scale * (float)qrow[d] + min_val;
        }
    }
}

// ============================================================================
// Buffer reader helper
// ============================================================================

struct buf_reader {
    const uint8_t * data;
    size_t size;
    size_t pos = 0;

    bool can_read(size_t n) const { return pos + n <= size; }

    template <typename T>
    bool read(T & val) {
        if (!can_read(sizeof(T))) return false;
        memcpy(&val, data + pos, sizeof(T));
        pos += sizeof(T);
        return true;
    }

    bool skip(size_t n) {
        if (!can_read(n)) return false;
        pos += n;
        return true;
    }

    const uint8_t * ptr() const { return data + pos; }
};

struct buf_writer {
    std::vector<uint8_t> & buf;

    template <typename T>
    void write(const T & val) {
        const uint8_t * p = reinterpret_cast<const uint8_t *>(&val);
        buf.insert(buf.end(), p, p + sizeof(T));
    }

    void write_bytes(const uint8_t * src, size_t n) {
        buf.insert(buf.end(), src, src + n);
    }
};

